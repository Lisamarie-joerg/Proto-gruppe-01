import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {registerHooks} from 'node:module';
const base=path.resolve('webapp/static'),url=p=>pathToFileURL(path.join(base,p)).href;
registerHooks({resolve(s,c,n){return s==='three'?n(url('three/three.module.js'),c):n(s,c);}});
globalThis.ProgressEvent=class{};
const {GLTFLoader}=await import(url('three/addons/loaders/GLTFLoader.js'));
const {sourceFromHost,sourceSignature,assignHosts}=await import(url('reuse-sources.js'));
const {buildPlan,DEFAULTS}=await import(url('reuse-core.js'));
const bytes=fs.readFileSync(path.join(base,'projekt6/Bauteil6.glb'));
const gltf=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
gltf.scene.rotation.x=Math.PI/2;gltf.scene.updateMatrixWorld(true);
const plan=JSON.parse(fs.readFileSync(path.join(base,'bauteil6-bewehrung.json')));
const meshes=[];gltf.scene.traverse(mesh=>{if(mesh.isMesh)meshes.push(mesh);});
const assigned=assignHosts(meshes,plan.hosts),sources=meshes.filter(mesh=>assigned.get(mesh)?.reinforcementExpected).map(mesh=>sourceFromHost(mesh,assigned.get(mesh)));
console.log('Sources',sources.length);
const result=buildPlan(sources,DEFAULTS,(i,n)=>{if(i%25===0)console.log(i+'/'+n);});
result.version='reuse-v1';result.sourceIds=sources.map(s=>s.id);result.sourceSignature=sourceSignature(sources);
fs.writeFileSync(path.join(base,'reuse-default-projekt6.json'),JSON.stringify(result));
console.log(JSON.stringify({parts:result.parts.length,cuts:result.cuts.length,trucks:result.trucks.length,mass:result.totalMass,audit:result.audit.reduce((a,x)=>(a[x.method]=(a[x.method]||0)+1,a),{})}));
